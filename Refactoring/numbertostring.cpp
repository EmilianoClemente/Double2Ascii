size_t ToChars(char* buf, double x, char separator, int n){
	uint64_t bits = *((uint64_t*)(&x));
	uint64_t mantissa = bits & 0xfffffffffffffUL;
	uint64_t f = mantissa | (0x1UL << 52);
	int exponent = (bits >> 52) & 0x7ff;
	int e, digits, gap;
	int edigit = 2;
	const lookup_t* lookup;
	size_t written = 0;

	if(exponent == 0x7ff){
		return handle_7ff(buf, mantissa);
	}

	if(bits >> 63){
		// minus
		*(buf++) = '-';
		written++;
	}

	if(exponent == 0){
		if(mantissa == 0){
			*buf = '0';
			buf[1] = separator;
			memset(buf + 2, '0', n - 1);
			buf[n + 1] = 'E';
			buf[n + 2] = '+';
			buf[n + 3] = '0';
			buf[n + 4] = '0';
			buf[n + 5] = 0;
			return n + 5 + written;
		}
		else{
			// subnormal number
			exponent = 1;
			f = mantissa;
		}
	}

	exponent = exponent - 1023 - 52;
	lookup = &(__lookup[exponent + 1076]);
	n++;	// handle as it has one more digit for later rounded

	f = f * lookup->coef;
	digits = ndigit(f);
	e = lookup->pow + digits - 1;

	gap = digits - n;

	while(gap > 4){
		f = div100_64bit(f);
		f = div100_64bit(f);
		gap = gap - 4;
	}

	while(gap > 1){
		f = div100_64bit(f);
		gap = gap - 2;
	}

	while(gap > 0){
		gap--;
		f = div10_64bit(f);
	}

	while(gap < 0){
		f = f * 10;
		gap ++;
	}

	if(e >= 100 || e <= -100){
		edigit = 3;
	}

	if(fast_mod10_u64(f) >= 5){
		f = f + 10;
		if(ndigit(f) != n){
			f = div10_64bit(f);
			e = e + 1;
		}
	}
	f = div10_64bit(f);
	n --;

	write_effective(buf + 1, f, n);
	*buf = buf[1];
	buf[1] = separator;

	buf[n + 1] = 'E';
	if(e < 0){
		buf[n+2] = '-';
		e = -1 * e;
	}
	else{
		buf[n+2] = '+';
	}

	write_effective(buf+n+3, e, edigit);

	buf[n + 3 + edigit] = 0;
	
	return written + n + 3 + edigit;
}

