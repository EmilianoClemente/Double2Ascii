static void write_effective(char* buf, uint64_t effective, int n){
	char* w = buf + (n - 1);
	char* p;
	while(w > buf){
		p = &(__2digits_lookup_table[fast_mod100_u64(effective) * 2 + 1]);
		effective = div100_64bit(effective);
		*(w--) = *(p--);
		*(w--) = *p;
	}

	if(w == buf){
		*w = fast_mod10_u64(effective) + '0';
	}
}

